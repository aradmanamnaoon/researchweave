from __future__ import annotations

from pathlib import Path

import pytest

from researchweave.evidence.errors import EvidenceError
from researchweave.evidence.library import LibraryService
from researchweave.evidence.storage import ProjectStore
from researchweave.evidence.synthesis import ASSESSMENT_DOMAINS, SynthesisService


def test_bias_template_catalog_is_versioned_and_not_claimed_official() -> None:
    templates = SynthesisService.bias_templates()
    ids = {item["id"] for item in templates}
    assert {"rob2-compatible-v1", "robins-i-compatible-v1"} <= ids
    assert all(item["version"] == 1 for item in templates)
    assert all(item["official_instrument"] is False for item in templates)
    assert all(item["definitive_judgments_require_verified_anchor"] for item in templates)


def test_definitive_bias_judgment_requires_verified_anchor(tmp_path: Path) -> None:
    with ProjectStore.create(
        tmp_path / "project", "Bias", "Question", "systematic_review"
    ) as store:
        library = LibraryService(store)
        imported = library.import_bibliography(
            b"@article{x,title={Synthetic Study},author={Doe, Ada},year={2024}}", "bibtex"
        )
        ref_id = imported["references"][0]["id"]
        store.mutate(
            "fixture.review",
            {"reference_id": ref_id},
            lambda conn: conn.execute(
                "INSERT INTO review_records(id,review_id,reference_id) VALUES (?,?,?)",
                ("record", "review", ref_id),
            ),
            expected_revision=None,
        )
        source = library.import_document(
            b"Random allocation sequence was generated by computer.", "Methods", "text/plain"
        )
        anchor = library.add_anchor(
            source["source_id"], "Random allocation sequence", 0, 26
        )["anchor_id"]
        template = "randomized-v1"
        responses = {
            domain: {"judgment": "unclear", "explanation": "Not reported"}
            for domain in ASSESSMENT_DOMAINS[template]
        }
        responses["randomization"] = {
            "judgment": "low",
            "explanation": "Computer-generated allocation was explicitly reported",
        }
        service = SynthesisService(store)
        with pytest.raises(EvidenceError, match="requires a verified source anchor"):
            service.assess_bias("record", template, "Reviewer", responses)
        responses["randomization"]["anchor_id"] = anchor
        saved = service.assess_bias("record", template, "Reviewer", responses)
        assert saved["domains"]["randomization"]["anchor_id"] == anchor
        assert saved["framework_certification"] == "compatible_workflow_not_official_instrument"
