"""Generate an auditable, deterministic index of repository-local agent skills.

Usage:
    python scripts/generate_skills_inventory.py
    python scripts/generate_skills_inventory.py --check
    python scripts/generate_skills_inventory.py --watch

The provenance document remains the authority for externally vendored skills.
No external code is executed and no files outside docs/SKILLS_INVENTORY.md are written.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
import time
from dataclasses import dataclass
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
SKILLS_DIR = ROOT / ".agents" / "skills"
PROVENANCE = ROOT / "docs" / "EXTERNAL_SKILLS_PROVENANCE.md"
OUTPUT = ROOT / "docs" / "SKILLS_INVENTORY.md"
FRONTMATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", flags=re.DOTALL)
WORDS = re.compile(r"\b[\w-]+\b")
NAME = re.compile(r"^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$")
PROVENANCE_ROW = re.compile(r"^\|\s*`([a-z][a-z0-9-]+)`\s*\|")


@dataclass(frozen=True)
class Skill:
    name: str
    description: str
    path: Path
    word_count: int
    support_files: int
    external: bool


def vendored_names() -> set[str]:
    """Treat the manually reviewed provenance table as the source of origin labels."""
    if not PROVENANCE.exists():
        raise ValueError(f"Missing external provenance document: {PROVENANCE}")
    names = {
        match.group(1)
        for line in PROVENANCE.read_text(encoding="utf-8").splitlines()
        if (match := PROVENANCE_ROW.match(line))
    }
    if not names:
        raise ValueError("External provenance table contains no skill rows")
    return names


def discover() -> list[Skill]:
    if not SKILLS_DIR.is_dir():
        raise ValueError(f"Missing skills directory: {SKILLS_DIR}")
    external = vendored_names()
    skills: list[Skill] = []
    names: set[str] = set()
    for folder in sorted(SKILLS_DIR.iterdir()):
        if not folder.is_dir():
            raise ValueError(f"Unexpected file in skills directory: {folder}")
        skill_file = folder / "SKILL.md"
        if not skill_file.is_file():
            raise ValueError(f"Missing SKILL.md: {folder}")
        content = skill_file.read_text(encoding="utf-8-sig")
        match = FRONTMATTER.match(content)
        if match is None:
            raise ValueError(f"Missing YAML frontmatter: {skill_file}")
        meta = yaml.safe_load(match.group(1))
        if not isinstance(meta, dict):
            raise ValueError(f"Frontmatter is not a mapping: {skill_file}")
        name, description = meta.get("name"), meta.get("description")
        if not isinstance(name, str) or not NAME.fullmatch(name):
            raise ValueError(f"Invalid skill name in {skill_file}: {name!r}")
        if name != folder.name:
            raise ValueError(f"Folder/frontmatter mismatch: {folder.name} != {name}")
        if name in names:
            raise ValueError(f"Duplicate skill name: {name}")
        if not isinstance(description, str) or not description.strip():
            raise ValueError(f"Missing skill description in {skill_file}")
        names.add(name)
        support_files = sum(1 for path in folder.rglob("*") if path.is_file()) - 1
        skills.append(
            Skill(
                name=name,
                description=" ".join(description.split()),
                path=skill_file,
                word_count=len(WORDS.findall(content[match.end() :])),
                support_files=support_files,
                external=name in external,
            )
        )
    missing = external - names
    if missing:
        raise ValueError("Vendored skills absent from repository: " + ", ".join(sorted(missing)))
    return skills


def md_cell(value: str) -> str:
    """Escape Markdown table delimiters and inline HTML that could disrupt rendering."""
    return (
        value.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace("|", "&#124;")
    )


def render(skills: list[Skill]) -> str:
    total = len(skills)
    external = sum(skill.external for skill in skills)
    support_files = sum(skill.support_files for skill in skills)
    words = sum(skill.word_count for skill in skills)
    lines = [
        "# Repository-local skills inventory",
        "",
        "<!-- Generated by scripts/generate_skills_inventory.py; do not edit by hand. -->",
        "",
        "This index lists every `.agents/skills/*/SKILL.md` currently present in the "
        "repository. Skill metadata is taken from its YAML frontmatter. "
        "The source of truth for vendored skill attribution and bundled license "
        "notices is [EXTERNAL_SKILLS_PROVENANCE.md](EXTERNAL_SKILLS_PROVENANCE.md).",
        "",
        f"**Total skills:** {total}",
        f"**Repository-authored skills:** {total - external}",
        f"**Vendored external skills:** {external}",
        f"**Additional files inside skill folders:** {support_files}",
        f"**Guidance words in SKILL.md bodies:** {words:,}",
        "",
        "| Skill | Activation / purpose | Origin | Guidance words | Supporting files |",
        "|---|---|---|---:|---:|",
    ]
    for skill in sorted(skills, key=lambda item: item.name):
        relative = f"../.agents/skills/{skill.name}/SKILL.md"
        # Full descriptions remain in source; limit table cells to aid scanning.
        summary = skill.description
        if len(summary) > 180:
            summary = summary[:179].rsplit(" ", 1)[0] + "…"
        source = "External (see provenance)" if skill.external else "Repository-authored"
        lines.append(
            f"| [`{skill.name}`]({relative}) | {md_cell(summary)} | {source} "
            f"| {skill.word_count:,} | {skill.support_files} |"
        )
    lines.extend(
        [
            "",
            "## Regeneration and validation",
            "",
            "These repository-maintenance helpers require PyYAML. Install the small "
            "tool-only dependency set with `python -m pip install -r scripts/requirements-tools.txt`.",
            "",
            "Run after skills are added, removed, renamed, or edited:",
            "",
            "```powershell",
            "python scripts/generate_skills_inventory.py",
            "```",
            "",
            "To make CI or local checks fail on a stale index without modifying files:",
            "",
            "```powershell",
            "python scripts/generate_skills_inventory.py --check",
            "```",
            "",
            "While parallel workers are adding skills, use `--watch` to regenerate on "
            "changes; stop it with Ctrl+C. The process observes local skill and "
            "provenance files only and makes no network calls.",
            "",
            "Run `python scripts/validate_skills.py` separately "
            "to check skill metadata and local references. Inventory counts "
            "measure document coverage, not evidence of implementation or skill quality.",
            "",
        ]
    )
    return "\n".join(lines)


def write_if_changed(content: str) -> bool:
    if OUTPUT.is_file() and OUTPUT.read_text(encoding="utf-8") == content:
        return False
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    temp_path: Path | None = None
    try:
        with tempfile.NamedTemporaryFile(
            mode="w",
            encoding="utf-8",
            newline="\n",
            dir=OUTPUT.parent,
            prefix=".skills-inventory-",
            suffix=".tmp",
            delete=False,
        ) as handle:
            temp_path = Path(handle.name)
            handle.write(content)
        os.replace(temp_path, OUTPUT)
    finally:
        if temp_path is not None:
            temp_path.unlink(missing_ok=True)
    return True


def update(check: bool) -> int:
    skills = discover()
    content = render(skills)
    if check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"STALE: {OUTPUT.relative_to(ROOT)}; regenerate inventory", file=sys.stderr)
            return 1
        print(f"OK: inventory up to date for {len(skills)} skills")
        return 0
    changed = write_if_changed(content)
    action = "Updated" if changed else "Unchanged"
    print(f"{action}: {OUTPUT.relative_to(ROOT)} ({len(skills)} skills)")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    options = parser.add_mutually_exclusive_group()
    options.add_argument("--check", action="store_true", help="fail if generated file is stale")
    options.add_argument("--watch", action="store_true", help="refresh index as skills change")
    args = parser.parse_args()
    try:
        if not args.watch:
            return update(check=args.check)
        print("Watching skill folders and provenance; Ctrl+C to stop.", flush=True)
        # Rendered content is an effective fingerprint of all metadata used by the inventory.
        # Poll rather than relying on OS-specific filesystem event libraries.
        while True:
            update(check=False)
            time.sleep(2)
    except KeyboardInterrupt:
        return 0
    except (OSError, ValueError, yaml.YAMLError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
