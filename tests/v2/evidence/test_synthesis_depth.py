from __future__ import annotations

from pathlib import Path

import pytest

from researchweave.evidence.errors import EvidenceError
from researchweave.evidence.library import LibraryService
from researchweave.evidence.reviews import ReviewService
from researchweave.evidence.storage import ProjectStore
from researchweave.evidence.synthesis import Finding, SynthesisService


def _record_anchor(store: ProjectStore) -> tuple[str, str]:
    library = LibraryService(store)
    source = library.import_document(
        b"Random allocation was generated by a computer. Outcome improved.",
        "Synthetic report",
        "text/plain",
    )
    body = library.source_text(source["source_id"])
    quote = "Random allocation was generated by a computer."
    start = body.index(quote)
    anchor = library.add_anchor(source["source_id"], quote, start, start + len(quote))
    reference = library.import_bibliography(
        b"@article{x,title={Synthetic RCT},author={Doe, Ada},year={2024}}", "bibtex"
    )
    record = ReviewService(store).register("review-1", reference["references"][0]["id"], "study-1")
    return record["record_id"], anchor["anchor_id"]


def test_bias_domains_preserve_uncertainty_and_verified_source_anchor(tmp_path: Path) -> None:
    root = tmp_path / "project"
    with ProjectStore.create(root, "Bias", "Question", "systematic_review") as store:
        record_id, anchor_id = _record_anchor(store)
        domains = {
            name: {
                "judgment": "low",
                "explanation": f"Synthetic rationale for {name}",
                "uncertainty": "moderate",
                "anchor_id": anchor_id,
            }
            for name in (
                "randomization",
                "deviations",
                "missing_outcomes",
                "outcome_measurement",
                "reported_result_selection",
            )
        }
        assessed = SynthesisService(store).assess_bias(
            record_id, "rob2-compatible-v1", "Reviewer", domains
        )
        assert assessed["overall"] == "requires_manual_interpretation"
        assert assessed["domains"]["randomization"]["anchor_id"] == anchor_id
        assert assessed["framework_certification"] == (
            "compatible_workflow_not_official_instrument"
        )
        invalid = {key: dict(value) for key, value in domains.items()}
        invalid["randomization"]["anchor_id"] = "missing"
        with pytest.raises(EvidenceError):
            SynthesisService(store).assess_bias(
                record_id, "rob2-compatible-v1", "Reviewer", invalid
            )
    with ProjectStore(root) as reopened:
        rows = SynthesisService(reopened).appraisals(record_id)
        assert rows[0]["responses"]["randomization"]["uncertainty"] == "moderate"
        assert reopened.audit()["ok"]


def test_gap_priority_resolution_history_and_traceable_synthesis_export(
    tmp_path: Path,
) -> None:
    root = tmp_path / "project"
    with ProjectStore.create(root, "Synthesis", "Question", "systematic_review") as store:
        record_id, anchor_id = _record_anchor(store)
        service = SynthesisService(store)
        gap = service.register_gap(
            "Do older adults have evidence?",
            [{"database": "Synthetic DB", "date": "2026-10-23", "strategy": "older adults"}],
            "No eligible synthetic records were identified.",
        )
        service.update_gap(gap["id"], "open", "high", "Important population gap.", "Reviewer")
        service.update_gap(gap["id"], "addressed", "high", "New study imported.", "Reviewer")
        recorded_gap = service.gaps()[0]
        assert recorded_gap["status"] == "addressed"
        assert recorded_gap["priority"] == "high"
        assert [row["status"] for row in recorded_gap["updates"]] == ["open", "addressed"]

        library = LibraryService(store)
        source_id = store.conn.execute(
            "SELECT source_id FROM anchors WHERE id=?", (anchor_id,)
        ).fetchone()[0]
        assert library.source_text(source_id)
        finding = service.add_finding(
            Finding(
                question="Effect?",
                population="Adults",
                outcome="Synthetic outcome",
                measure="mean difference",
                unit="points",
                timepoint="8 weeks",
                direction="positive",
                statement="The synthetic report described improvement.",
                anchor_id=anchor_id,
            )
        )
        outline = service.compose(
            "Narrative synthesis",
            [
                {
                    "heading": "Outcome",
                    "narrative": "A cautious human-written synthesis.",
                    "finding_ids": [finding["id"]],
                }
            ],
        )
        exported = service.export_outline_markdown(outline["id"])
        assert f"anchor={anchor_id}" in exported
        assert "Scientific conclusions are not automatically verified" in exported
        assert record_id
